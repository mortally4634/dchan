CREATE TABLE IF NOT EXISTS ``posts_{{ board }}`` (
   `id` int(11) unsigned NOT NULL AUTO_INCREMENT,
   `thread` int(11) DEFAULT NULL,
   `subject` varchar(100) DEFAULT NULL,
   `email` varchar(30) DEFAULT NULL,
   `name` varchar(35) DEFAULT NULL,
   `trip` varchar(15) DEFAULT NULL,
   `capcode` varchar(50) DEFAULT NULL,
   `body` text NOT NULL,
   `body_nomarkup` text,
   `time` int(11) NOT NULL,
   `bump` int(11) DEFAULT NULL,
   `files` text DEFAULT NULL,
   `num_files` int(11) DEFAULT 0,
   `filehash` text CHARACTER SET ascii,
   `password` varchar(64) DEFAULT NULL,
   `ip` varchar(39) CHARACTER SET ascii NOT NULL,
   `sticky` int(1) NOT NULL,
   `locked` int(1) NOT NULL,
   `cycle` int(1) NOT NULL,
   `sage` int(1) NOT NULL,
   `embed` text,
   `slug` varchar(256) DEFAULT NULL,
   `approved` tinyint(1) NOT NULL DEFAULT 1 COMMENT 'File pending approval: 0 = pending, 1 = approved',
   `approved_link` tinyint(1) NOT NULL DEFAULT 1 COMMENT 'Link pending approval: 0 = pending, 1 = approved',
   `cookie_id` varchar(64) CHARACTER SET ascii DEFAULT NULL COMMENT 'Persistent per-visitor cookie id',
   `hwid` varchar(64) CHARACTER SET ascii DEFAULT NULL COMMENT 'Device fingerprint (header-derived)',
   `is_vpn` tinyint(1) NOT NULL DEFAULT 0 COMMENT 'Poster IP flagged as VPN/proxy',
   `show_poster_id` tinyint(1) NOT NULL DEFAULT 0 COMMENT 'Poster opted to show a per-post Poster ID',
   `mod_id` int(11) DEFAULT NULL COMMENT 'Posting mod user id (used as the SID on staff boards)',
   `fp_hash` varchar(32) CHARACTER SET ascii DEFAULT NULL COMMENT 'Client browser fingerprint (imgboard_fp)',
   UNIQUE KEY `id` (`id`),
   KEY `thread_id` (`thread`,`id`),
   KEY `filehash` (`filehash`(40)),
   KEY `time` (`time`),
   KEY `ip` (`ip`),
   KEY `list_threads` (`thread`, `sticky`, `bump`)
 ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 AUTO_INCREMENT=1 ;
 
